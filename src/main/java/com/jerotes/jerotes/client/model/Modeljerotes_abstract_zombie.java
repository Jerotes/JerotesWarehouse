	public void setupAnim(T t, float p_102002_, float p_102003_, float p_102004_, float p_102005_, float p_102006_) {
		super.setupAnim(t, p_102002_, p_102003_, p_102004_, p_102005_, p_102006_);
		if (!(t instanceof FingerOfDeathZombieEntity fingerOfDeathZombieEntity)) {
			AnimationUtils.animateZombieArms(this.leftArm, this.rightArm, this.isAggressive(t), this.attackTime, p_102004_);
		}
		else if ((InventoryEntity.isMeleeWeapon(fingerOfDeathZombieEntity, fingerOfDeathZombieEntity.getMainHandItem()) || fingerOfDeathZombieEntity.getMainHandItem().isEmpty()) && !t.isUsingItem() || t.isAggressive()) {
			AnimationUtils.animateZombieArms(this.leftArm, this.rightArm, this.isAggressive(t), this.attackTime, p_102004_);
		}
	}

	public abstract boolean isAggressive(T p_101999_);
